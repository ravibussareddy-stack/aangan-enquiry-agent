/**
 * Generate db/seed.sql from db/seed/{config,rates}.json.
 * Idempotent: config upserts keep values the founder has already edited.
 *
 *   npm run seed:sql
 */
import { readFileSync, writeFileSync } from "node:fs";

interface ConfigRow {
  value: unknown;
  description?: string;
  needs_founder_signoff?: boolean;
  server_only?: boolean;
}
interface RateRow {
  component: string;
  unit: string;
  unit_rate_inr: number;
  effective_from: string;
  note?: string;
}

const lit = (s: string | undefined | null) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);

const config: Record<string, ConfigRow> = JSON.parse(readFileSync("db/seed/config.json", "utf8"));
const rates: RateRow[] = JSON.parse(readFileSync("db/seed/rates.json", "utf8"));

const configValues = Object.entries(config).map(
  ([key, row]) =>
    `  (${lit(key)}, ${lit(JSON.stringify(row.value))}::jsonb, ${lit(row.description)}, ${row.needs_founder_signoff ?? false}, ${row.server_only ?? false})`,
);
const rateValues = rates.map(
  (r) => `  (${lit(r.component)}, ${lit(r.unit)}, ${r.unit_rate_inr}, ${lit(r.effective_from)}, ${lit(r.note)})`,
);

const sql = `-- GENERATED by scripts/gen-seed-sql.ts from db/seed/*.json — do not edit by hand.

insert into config (key, value, description, needs_founder_signoff, server_only) values
${configValues.join(",\n")}
on conflict (key) do update set
  description = excluded.description,
  needs_founder_signoff = excluded.needs_founder_signoff,
  server_only = excluded.server_only;

insert into rates (component, unit, unit_rate_inr, effective_from, note) values
${rateValues.join(",\n")}
on conflict (component, unit, effective_from) do nothing;
`;

writeFileSync("db/seed.sql", sql);
console.log(`Wrote db/seed.sql (${configValues.length} config keys, ${rateValues.length} rates)`);
